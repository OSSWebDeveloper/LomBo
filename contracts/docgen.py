def add_months(d: date, months: int) -> date:
    """Sanaga oy qo'shish (kun oshib ketsa oy oxirgi kuniga tushiriladi)."""
    month = d.month - 1 + months
    year = d.year + month // 12
    month = month % 12 + 1
    if month == 12:
        next_first = date(year + 1, 1, 1)
    else:
        next_first = date(year, month + 1, 1)
    last_day = (next_first - timedelta(days=1)).day
    return date(year, month, min(d.day, last_day))


def contract_end_date(start: date, months: int) -> date:
    """Shartnoma tugash sanasi: boshlanish + muddat − 1 kun.
    Namunadagidek 03.11.2025 + 12 oy -> 02.11.2026."""
    return add_months(start, months) - timedelta(days=1)


# ------------------------------------------------------------------ helpers

# Asl shartnoma fayllaridagi o'lchamlar
BODY_PT = 12          # asosiy matn
TITLE_PT = 14         # sarlavhalar
CELL_PT = 11          # jadval katagi
PAGE_W, PAGE_H = 21.0, 29.7                  # A4, sm
MARGIN_L, MARGIN_R, MARGIN_T, MARGIN_B = 2.2, 1.5, 1.3, 1.6


def _sana(d: date) -> str:
    return d.strftime('%d.%m.%Y')


def _pul(n) -> str:
    """35000000 -> «35 000 000 (ўттиз беш миллион)»"""
    return f'{summa_formatlangan(n)} ({num2words_uz(n)})'


def _vergul(n) -> str:
    """21.95 -> «21,95» (mahalliy o'nlik ajratkichi)"""
    return f'{n}'.replace('.', ',')


def _p(doc, text, *, bold=False, center=False, size=BODY_PT, space_after=4, indent=True):
    par = doc.add_paragraph()
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.JUSTIFY
    fmt = par.paragraph_format
    fmt.space_after = Pt(space_after)
    fmt.space_before = Pt(0)
    if indent and not center:
        fmt.first_line_indent = Cm(1.0)
    run = par.add_run(text)
    run.bold = bold
    run.font.size = Pt(size)
    run.font.name = 'Times New Roman'
    return par


def _two_col(doc, left_text, right_text, size=BODY_PT):
    """Chap-o'ng ikki ustunli qator (masalan, sana — shahar)."""
    table = doc.add_table(rows=1, cols=2)
    table.autofit = True
    for i, (txt, align) in enumerate([(left_text, WD_ALIGN_PARAGRAPH.LEFT),
                                      (right_text, WD_ALIGN_PARAGRAPH.RIGHT)]):
        cell = table.cell(0, i)
        par = cell.paragraphs[0]
        par.alignment = align
        run = par.add_run(txt)
        run.font.size = Pt(size)
        run.font.name = 'Times New Roman'
    return table


def _new_doc():
    doc = Document()
    style = doc.styles['Normal']
    style.font.name = 'Times New Roman'
    style.font.size = Pt(BODY_PT)
    # Kirill uchun ham shrift nomini o'rnatish
    rpr = style.element.get_or_add_rPr()
    rfonts = rpr.get_or_add_rFonts()
    rfonts.set(
        '{http://schemas.openxmlformats.org/wordprocessingml/2006/main}cs', 'Times New Roman')
    for section in doc.sections:
        # Asl shartnomalardagidek A4 (python-docx standarti — Letter)
        section.page_width = Cm(PAGE_W)
        section.page_height = Cm(PAGE_H)
        section.top_margin = Cm(MARGIN_T)
        section.bottom_margin = Cm(MARGIN_B)
        section.left_margin = Cm(MARGIN_L)
        section.right_margin = Cm(MARGIN_R)
    return doc


def _table_cell(cell, text, *, bold=False, center=True, size=CELL_PT):
    par = cell.paragraphs[0]
    par.alignment = WD_ALIGN_PARAGRAPH.CENTER if center else WD_ALIGN_PARAGRAPH.LEFT
    run = par.add_run(str(text))
    run.bold = bold
    run.font.size = Pt(size)
    run.font.name = 'Times New Roman'



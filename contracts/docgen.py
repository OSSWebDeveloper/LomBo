def _ctx(contract):
    org = settings.LOMBARD_ORG
    c = contract
    return {
        'org': org,
        'number': c.number,
        'sana': _sana(c.date),
        'sana_end': _sana(c.end_date),
        'fio': c.borrower_fio,
        'passport': c.passport_full,
        'address': c.borrower_address,
        'phone': c.borrower_phone or '____________',
        'amount': _pul(c.amount),
        'term': c.term_months,
        'term_soz': num2words_uz(c.term_months),
        'rate': c.interest_rate,
        'rate_soz': num2words_uz(c.interest_rate),
        # Butun to'plam shartnomaning bitta raqami bilan yuritiladi
        'garov_number': c.number,
        'garov_value': _pul(c.garov_value) if c.garov_value else '',
    }


def _taminot_matni(contract, ctx):
    """1.1-bandning ta'minot haqidagi dinamik qismi."""
    if contract.collateral_type == contract.TYPE_ZARGARLIK:
        return (f'накд пулда, гаров таъминоти сифатида, {ctx["fio"]}га тегишли '
                f'заргарлик буюмларини гаровга қўяди.')
    if contract.collateral_type == contract.TYPE_TRANSPORT:
        v = contract.vehicle
        return (f'накд пулда, гаров таъминоти сифатида, {v.owner}га тегишли, '
                f'давлат рақами {v.state_number} бўлган, {v.model} русумли '
                f'транспорт воситаси гаровга қўйилади.')
    g = contract.guarantor
    return (f'накд пулда, таъминоти сифатида {g.fio}нинг {_pul(g.amount)} сўмлик '
            f'иш ҳақи кафиллиги тақдим қилинади.')



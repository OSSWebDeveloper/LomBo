def build_contract_docx_eski(contract) -> bytes:
    """Eski usul: matn koddan yoziladi. Zaxira sifatida saqlanmoqda."""
    ctx = _ctx(contract)
    doc = _new_doc()

    _mikroqarz_shartnoma(doc, contract, ctx)
    if contract.collateral_type in (contract.TYPE_ZARGARLIK, contract.TYPE_TRANSPORT):
        _garov_shartnoma(doc, contract, ctx)
        _dalolatnoma(doc, contract, ctx)
    _jadval(doc, contract, ctx)

    buf = io.BytesIO()
    doc.save(buf)
    return buf.getvalue()
